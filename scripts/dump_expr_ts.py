#!/usr/bin/env python3

from __future__ import annotations

import base64
import json

from mechbench_compute import __version__
from mechbench_compute.expr.engine import ENGINE_SHA256, ENGINE_VERSION, WASM_PATH, verify_wasm


def main() -> None:
    data = WASM_PATH.read_bytes()
    verify_wasm(data)
    print("// GENERATED by mechbench-compute scripts/dump_expr_ts.py "
          f"({__version__}). Do not edit by hand.")
    print("// The source is mechbench_compute/expr/mbexpr.wasm, the expression engine compute pins; "
          "re-run the script after re-pinning it.")
    print()
    print(f"export const EXPR_ENGINE_VERSION = {json.dumps(ENGINE_VERSION)};")
    print(f"export const EXPR_ENGINE_SHA256 = {json.dumps(ENGINE_SHA256)};")
    print(f"export const EXPR_ENGINE_BYTES = {len(data)};")
    print(f"export const EXPR_ENGINE_WASM_BASE64 = {json.dumps(base64.b64encode(data).decode())};")


if __name__ == "__main__":
    main()
