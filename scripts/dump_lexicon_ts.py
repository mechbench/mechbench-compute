#!/usr/bin/env python3
"""Write the operation lexicon for a TypeScript consumer.

The protocol composer renders every node's editor from the declaration:
each op's ports, and each parameter's type, default, closed set and
fields. The lexicon (`mechbench_compute/lexicon/`) is the one place those
are declared, so this script writes them as a TypeScript module the UI
commits verbatim, and `tests/test_lexicon_ts.py` fails when the committed
copy no longer matches.

Only what an editor reads is written: an op's long description and its
emitted record's prose live on the documentation site, which a parameter's
help links to.

Usage:
    python scripts/dump_lexicon_ts.py > ../mechbench-ui/src/lib/lexicon.generated.ts
"""

from __future__ import annotations

import json
import sys
from typing import Any

from mechbench_compute import __version__, lexicon
from mechbench_compute.lexicon._base import ROOT

HEADER = """\
// GENERATED by mechbench-compute scripts/dump_lexicon_ts.py ({version}). Do not edit by hand.
// The source is mechbench_compute/lexicon/; re-run the script after changing it.
"""

TYPES = """\
/** One parameter of an operation, or one field of a structured parameter. */
export interface LexiconParam {
  name: string;
  /** A type in the lexicon's grammar: `int`, `"all" | list[int]`, `map[string, string]`. */
  type: string;
  doc: string;
  required: boolean;
  /** The value the block uses when the param is absent. Present only when not required. */
  default?: unknown;
  /** The closed set every `string` in the type takes. */
  choices?: string[];
  /** The shared value this param's structure is: `pool`, `point`. */
  value?: string;
  /** The fields of every `object` in the type. */
  fields?: LexiconParam[];
}

/** One input port. */
export interface LexiconPort {
  name: string;
  kind: string;
  kinds: string[];
  doc: string;
  required: boolean;
  many: boolean;
  variadic: boolean;
  on_missing: string;
  min_edges?: number;
  max_edges?: number;
}

export interface LexiconOp {
  name: string;
  path: string;
  title: string;
  family: string;
  requires: "pure" | "mlx-local" | "remote" | "by-model";
  summary: string;
  inputs: LexiconPort[];
  /** What it emits, and — under `otherwise` — what it emits instead when
   * a param has a value or an input port is filled. */
  emits: {
    kind: string;
    collection: boolean;
    otherwise?: { kind: string; collection: boolean; when: { param: string; equals: unknown } | { port: string } }[];
  } | null;
  params: LexiconParam[];
  example: Record<string, unknown> | null;
  example_inputs: Record<string, unknown> | null;
}

/** A shared value: a structure or vocabulary many params take. */
export interface LexiconValue {
  name: string;
  summary: string;
  grammar: boolean;
  fields: LexiconParam[];
  choices?: string[];
}
"""


def _value_fields(v: Any) -> list[dict[str, Any]]:
    out = []
    for name, spec in v.fields.items():
        d: dict[str, Any] = {"name": name, "type": spec["type"], "doc": spec["description"],
                             "required": name in v.required}
        if name not in v.required and "default" in spec:
            d["default"] = spec["default"]
        if spec.get("choices"):
            d["choices"] = list(spec["choices"])
        out.append(d)
    return out


def _op(op: Any) -> dict[str, Any]:
    d = op.to_dict()
    for gone in ("description",):
        d.pop(gone)
    if d["emits"]:
        d["emits"] = {k: v for k, v in d["emits"].items() if k != "doc"}
    return d


def main(out: Any = sys.stdout) -> None:
    w = out.write
    w(HEADER.format(version=__version__))
    w("\n")
    w(TYPES)
    w("\n")
    w(f"export const OP_ROOT = {json.dumps(ROOT)};\n\n")
    w("/** Every operation, by name. */\n")
    w("export const OPS: Record<string, LexiconOp> = ")
    w(json.dumps({op.name: _op(op) for op in lexicon.OPS}, indent=1, ensure_ascii=False))
    w(";\n\n")
    w("/** The parameters every operation accepts: the wiring, not the operation. */\n")
    w("export const COMMON_PARAMS: LexiconParam[] = ")
    w(json.dumps([p.to_dict() for p in lexicon.COMMON], indent=1, ensure_ascii=False))
    w(";\n\n")
    w("/** The parameter grammars a param can name as its `value`. */\n")
    w("export const VALUES: Record<string, LexiconValue> = ")
    values = {}
    for v in lexicon.VALUES:
        if not v.grammar:
            continue
        d: dict[str, Any] = {"name": v.name, "summary": v.summary, "grammar": v.grammar,
                             "fields": _value_fields(v)}
        if v.choices:
            d["choices"] = list(v.choices)
        values[v.name] = d
    w(json.dumps(values, indent=1, ensure_ascii=False))
    w(";\n")


if __name__ == "__main__":
    main()
