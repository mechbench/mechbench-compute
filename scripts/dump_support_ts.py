#!/usr/bin/env python3

from __future__ import annotations

import json

from mechbench_compute import __version__, support
from mechbench_compute.providers import pricing


def _ts(value) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    print("// GENERATED by mechbench-compute scripts/dump_support_ts.py "
          f"({__version__}). Do not edit by hand.")
    print("// The source is mechbench_compute/support.py and the provider registry and price "
          "table; re-run the script after changing them.")
    print()
    print("/** How deep compute reaches into a local architecture: `full` is every hook point, `core` "
          "a subset, `text` none. */")
    print("export type SupportLevel = " + " | ".join(_ts(k) for k in support.LEVELS) + ";")
    print()
    print("export const SUPPORT_LEVELS: Record<SupportLevel, string> = {")
    for k, v in support.LEVELS.items():
        print(f"  {k}: {_ts(v)},")
    print("};")
    print()
    print("/** A local architecture compute loads: a checkpoint's config.json `model_type`, the "
          "library that loads it, what it supports, and the config keys that make compute refuse "
          "a checkpoint of it anyway. */")
    print("export interface LocalArchitecture {")
    print("  modelType: string;")
    print("  name: string;")
    print("  loader: " + " | ".join(_ts(x) for x in support.LOADERS) + ";")
    print("  level: SupportLevel;")
    print("  generate: boolean;")
    print("  score: boolean;")
    print("  train: boolean;")
    print("  layerPoints: string[];")
    print("  globalPoints: string[];")
    print("  refusedWhen: { configKey: string; reason: string }[];")
    print("}")
    print()
    print("export const LOCAL_ARCHITECTURES: LocalArchitecture[] = [")
    for a in support.local_architectures():
        print(f"  {_ts(a)},")
    print("];")
    print()
    print("/** A provider model with its price in US dollars per million tokens. A price applies to "
          "every model id that starts with `model`. `reasoning` says the provider's adapter keeps a "
          "model's reasoning as its own content; `tools` that it passes tools. A cache price that is "
          "null is the input price. */")
    print("export interface ProviderModel {")
    print("  provider: string;")
    print("  model: string;")
    print("  inputPerMillion: number;")
    print("  outputPerMillion: number;")
    print("  cacheReadPerMillion: number | null;")
    print("  cacheWritePerMillion: number | null;")
    print("  cacheWrite1hPerMillion: number | null;")
    print("  effortLevels: string[];")
    print("  reasoningDisplays: string[];")
    print("  promptCache: boolean;")
    print("  reasoning: boolean;")
    print("  tools: boolean;")
    print("}")
    print()
    print(f"export const PRICE_TABLE_VERSION = {_ts(pricing.TABLE_VERSION)};")
    print()
    print("export const PROVIDER_MODELS: ProviderModel[] = [")
    for m in support.provider_models():
        print(f"  {_ts(m)},")
    print("];")


if __name__ == "__main__":
    main()
