#!/usr/bin/env python3

from __future__ import annotations

import json

from mechbench_compute import __version__
from mechbench_compute.lexicon import kinds as K
from mechbench_compute.lexicon._base import COLLECTION, KIND_ROOT
from mechbench_compute.registry import CORE


def main() -> None:
    print("// GENERATED by mechbench-compute scripts/dump_kinds_ts.py "
          f"({__version__}). Do not edit by hand.")
    print("// The source is mechbench_compute/lexicon/kinds/, one file per kind; re-run the script after changing it.")
    print()
    print(f"export const COLLECTION = {json.dumps(COLLECTION)};")
    print(f"export const KIND_ROOT = {json.dumps(KIND_ROOT)};")
    print()
    print("/** Every declared kind, by bare name: its key, whether a collection of it exists, and the kind it")
    print(" * extends — which is what lets an object fill a port declared as its ancestor — and the fields it")
    print(" * declares itself (an ancestor's are its ancestor's); its sentence (`speak`, a template over an")
    print(" * item's fields and `header.*`), its chart (`draw`) and its notable line (`notable`, how a try's")
    print(" * result is read against its baseline) when it has them. `subfields` holds the")
    print(" * fields a read may name one level down, by the prefix the expression engine spells (`space` for")
    print(" * `space.layer`, `top[]` for `top[0].token`), where the kind closes them; a prefix it does not")
    print(" * list is open. */")
    print("export const KINDS: Record<string, { key: string[]; collectable: boolean; platform: boolean; "
          "extends: string | null; fields: string[]; subfields?: Record<string, string[]>; summary: string; speak?: string; "
          "draw?: { mark: string; encoding: Record<string, string> }; notable?: { field: string; key: string[]; "
          "metric: string; threshold: number; line: string; control?: Record<string, unknown> }; version: number }> = {")
    for k in CORE.kinds():
        said = f", speak: {json.dumps(k.speak)}" if k.speak else ""
        drawn = f", draw: {json.dumps(k.draw.to_dict())}" if k.draw else ""
        noted = f", notable: {json.dumps(k.notable.to_dict())}" if k.notable else ""
        subs = {p: list(names) for p, names in k.subfields.items()}
        closed = f", subfields: {json.dumps(subs)}" if subs else ""
        print(f"  {json.dumps(k.name)}: {{ key: {json.dumps(list(k.key))}, collectable: {json.dumps(k.collectable)}, "
              f"platform: {json.dumps(k.platform)}, extends: {json.dumps(k.extends)}, "
              f"fields: {json.dumps(list(k.fields))}{closed}, summary: {json.dumps(k.summary)}{said}{drawn}{noted}, "
              f"version: {k.version} }},")
    print("};")
    print()
    print("/** Retired spelling → [bare kind name, was it a collection]. */")
    print("export const KIND_ALIASES: Record<string, [string, boolean]> = {")
    for old, (name, plural) in K.KIND_ALIASES.items():
        print(f"  {json.dumps(old)}: [{json.dumps(name)}, {json.dumps(plural)}],")
    print("};")
    print()
    print("/** Retired plural kind → the field its items lived in. */")
    print("export const LEGACY_ITEMS_FIELD: Record<string, string> = {")
    for old, field in K._LEGACY_ITEMS_FIELD.items():
        print(f"  {json.dumps(old)}: {json.dumps(field)},")
    print("};")


if __name__ == "__main__":
    main()
