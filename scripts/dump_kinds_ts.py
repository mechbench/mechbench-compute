#!/usr/bin/env python3
"""Write the kind alias table for a TypeScript consumer.

The lexicon (`mechbench_compute/lexicon/kinds.py`) is the one declaration
of every kind and of every retired spelling. The UI reads stored objects
written across releases, so it needs the same table; this script writes
it as a TypeScript module the UI commits verbatim.

Usage:
    python scripts/dump_kinds_ts.py > ../mechbench-ui/src/lib/kindAliases.generated.ts
"""

from __future__ import annotations

import json

from mechbench_compute import __version__
from mechbench_compute.lexicon import kinds as K
from mechbench_compute.lexicon._base import COLLECTION, KIND_ROOT


def main() -> None:
    print("// GENERATED by mechbench-compute scripts/dump_kinds_ts.py "
          f"({__version__}). Do not edit by hand.")
    print("// The source is mechbench_compute/lexicon/kinds.py; re-run the script after changing it.")
    print()
    print(f"export const COLLECTION = {json.dumps(COLLECTION)};")
    print(f"export const KIND_ROOT = {json.dumps(KIND_ROOT)};")
    print()
    print("/** Every declared kind, by bare name, with its key and whether a collection of it exists. */")
    print("export const KINDS: Record<string, { key: string[]; collectable: boolean; platform: boolean; summary: string }> = {")
    for k in K.KINDS:
        print(f"  {json.dumps(k.name)}: {{ key: {json.dumps(list(k.key))}, collectable: {json.dumps(k.collectable)}, "
              f"platform: {json.dumps(k.platform)}, summary: {json.dumps(k.summary)} }},")
    print("};")
    print()
    print("/** Retired spelling → [bare kind name, was it a collection]. */")
    print("export const KIND_ALIASES: Record<string, [string, boolean]> = {")
    for old, (name, plural) in K.KIND_ALIASES.items():
        print(f"  {json.dumps(old)}: [{json.dumps(name)}, {json.dumps(plural)}],")
    print("};")
    print()
    print("/** Retired plural kind → the field its items lived in. */")
    print("export const LEGACY_ITEMS_FIELD: Record<string, string> = {")
    for old, field in K._LEGACY_ITEMS_FIELD.items():
        print(f"  {json.dumps(old)}: {json.dumps(field)},")
    print("};")


if __name__ == "__main__":
    main()
